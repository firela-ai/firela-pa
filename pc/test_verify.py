#!/usr/bin/env python3
"""数字对账门攻击样本测试 — issue #3 验收 ③/④。

攻击 = 个人数据断言含不可溯源数字（必须拦截）；反例 = 概念示例/白名单/问句自带数字
（必须原样通过，误杀 0）。跑法：python3 pc/test_verify.py
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from verify import FALLBACK, gate

FAILS = []


def blocked(q, a, why):
    out = gate(q, a)
    if out != FALLBACK:
        FAILS.append(("MISS-BLOCK", why, q, a, out))


def passed(q, a, why):
    out = gate(q, a)
    if out != FALLBACK:
        return
    FAILS.append(("FALSE-BLOCK", why, q, a, out))


# ---- 攻击：编造个人财务数据（tx/pf/c 误路由进生成腿的典型形态）----
blocked("我的余额还有多少", "你的余额是 3,000 元，够用。", "余额+千分位编造")
blocked("这个月花了多少", "本月你总共花了 1280.5 元。", "支出金额编造")
blocked("我该怎么理财", "你的存款有 38 万，可以先还房贷。", "万进位编造")
blocked("帮我看看资产", "你的资产约 12.5 万元，配置偏保守。", "小数万进位编造")
blocked("最近支出如何", "你的支出为 3,456.78 元。", "千分位小数编造")
blocked("贵州茅台多少钱", "贵州茅台股价 1450 元左右。", "股价编造")
blocked("我工资多少来着", "你上月工资收入 18500 元。", "工资编造（工资/收入双关键词）")

# ---- 反例：概念示例/白名单/问句自带（误杀必须为 0）----
passed("什么是复利", "复利就是利滚利，比如 100 元年利率 3%，一年后约 103 元。", "无个人断言的示例数字")
passed("什么是4%法则", "4% 法则指退休后每年支取 4% 的资产。", "白名单：4% 法则（资产邻近）")
passed("一般储蓄率多少算健康", "通常储蓄率 20% 到 30% 就比较健康。", "白名单：储蓄率常见档")
passed("FIRE要存多少钱", "一般建议存 25 倍年支出。", "白名单：25 倍法则")
passed("我工资卡里有38万，该怎么理财", "你提到有 38 万，建议先留 3-5 万应急金。", "问句自带数字（38万/万进位归一）")
passed("晚安", "晚安，好梦。", "无数字")
passed("什么是指数基金", "指数基金长期年化约 8%，适合定投。", "无个人断言（指数点数天花板已注记）")

# 问句数字与回答写法不一致的归一（千分位 ↔ 万）
q = "账户里有 1,250,000 元吗"
passed(q, "你说的 125 万可以做稳健配置。", "125 万 ↔ 1,250,000 归一匹配")

# ---- 中文数字支（2026-09-23 r2 §4-2 共享原语；有界文法）----
blocked("我该怎么理财", "你的存款有三十万元，建议先还房贷。", "中文数字编造（三十万）")
blocked("帮我看看资产", "你的资产约一百二十万，配置偏保守。", "中文数字编造（一百二十万复合）")
blocked("最近支出如何", "你这个月支出有两千五百元。", "中文数字编造（两千五百）")
passed("我存款有三十万该怎么理财", "这三十万建议分三笔做稳健配置。", "问句自带中文数字（三十万归一）")
passed("万一余额不足怎么办", "万一余额不足，可以设置自动转账补足。", "「万一」非数字（单位收尾规则防误杀）")
passed("什么是FIRE", "存到年支出的二十五倍即可考虑退休。", "中文数字命中白名单（二十五=25）")
passed("我账户里有300万该怎么理财", "这300万可以分三笔配置。", "「300万」裸单位不二次提取（OCR R1：_NUM_RE 整体 3e6）")
blocked("我该怎么理财", "你的负债有三亿五千万，建议尽快处置。", "亿+万混合层级（OCR R1：3.05e8）")
import verify as _v


def _zh_ok(cond, why):
    if not cond:
        FAILS.append(why)


_zh_ok(_v._zh_to_value("三亿五千万") == 350_000_000, "三亿五千万须=3.5e8（三亿+五千万）")
_zh_ok(_v._zh_to_value("三十万") == 300_000, "三十万须=3e5")
_zh_ok(_v._zh_to_value("三万亿") == 3_000_000_000_000, "三万亿须=3e12")
_zh_ok(_v._nums("余额300万") == {3_000_000.0}, f"「300万」提取须单值 3e6（得 {_v._nums('余额300万')}）")

if FAILS:
    for f in FAILS:
        print(f)
    sys.exit(1)
print("verify gate: all fixtures passed "
      f"({10} attack blocked + {11} reverse passed, 固有数字误杀 0)")
